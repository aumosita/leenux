# Colors
COLOR_BG = 0x00F5F5DC
COLOR_TEXT = 0x00000000
COLOR_PROMPT = 0x000066CC
COLOR_CURSOR = 0x00000000

class KoreanTerminal:
    def __init__(self):
        self.cursor_x = 0
        self.cursor_y = 0
        self.command_line = ""
        self.cursor_visible = True
        self.last_blink = time.time()
        self.history = []
        
        # Load Korean font
        self.korean_font = None
        for font_path in KOREAN_FONT_PATHS:
            if os.path.exists(font_path):
                try:
                    self.korean_font = ImageFont.truetype(font_path, 14)
                    print(f"✓ Loaded Korean font: {font_path}")
                    break
                except:
                    continue
        
        if not self.korean_font:
            print("⚠️  Korean font not found, using fallback")
            self.korean_font = ImageFont.load_default()
    
    def draw_char_bitmap(self, fb, x, y, char, color):
        """Draw ASCII character using bitmap font"""
        if char not in FONT_5X8:
            return
        char_data = FONT_5X8[char]
        for row in range(8):
            byte = char_data[row]
            for bit in range(5):
                if byte & (0x10 >> bit):
                    px = x + bit
                    py = y + row
                    if 0 <= px < WIDTH and 0 <= py < HEIGHT:
                        offset = (py * WIDTH + px) * 4
                        fb[offset:offset+4] = struct.pack('<I', color)
    
    def draw_char_pil(self, fb, x, y, char, color):
        """Draw Unicode character using PIL"""
        # Create small image for this character
        img = Image.new('RGBA', (16, 16), (245, 245, 220, 255))  # Beige background
        draw = ImageDraw.Draw(img)
        
        # Draw character
        rgb = ((color >> 16) & 0xFF, (color >> 8) & 0xFF, color & 0xFF)
        draw.text((0, 0), char, font=self.korean_font, fill=rgb)
        
        # Copy to framebuffer
        pixels = img.load()
        for dy in range(16):
            for dx in range(16):
                px = x + dx
                py = y + dy
                if 0 <= px < WIDTH and 0 <= py < HEIGHT:
                    r, g, b, a = pixels[dx, dy]
                    if a > 128:  # Only draw if not transparent
                        offset = (py * WIDTH + px) * 4
                        fb[offset:offset+4] = struct.pack('BBBB', b, g, r, 255)
    
    def draw_string(self, fb, x, y, text, color):
        """Draw mixed ASCII/Korean text"""
        cx = x
        for char in text:
            if ord(char) < 128 and char in FONT_5X8:
                # ASCII: use bitmap
                self.draw_char_bitmap(fb, cx, y, char, color)
                cx += 6
            else:
                # Korean/Unicode: use PIL
                self.draw_char_pil(fb, cx, y, char, color)
                cx += 14  # Korean characters wider
    
    def update_blink(self):
        now = time.time()
        if now - self.last_blink > 0.5:
            self.cursor_visible = not self.cursor_visible
            self.last_blink = now
    
    def render(self, fb):
        # Clear screen
        for i in range(0, len(fb), 4):
            fb[i:i+4] = struct.pack('<I', COLOR_BG)
        
        # Draw history
        y_offset = 10
        for line in self.history[-25:]:
            self.draw_string(fb, 10, y_offset, line, COLOR_TEXT)
            y_offset += 12
        
        # Draw prompt
        self.draw_string(fb, 10, y_offset, "leenux> ", COLOR_PROMPT)
        
        # Draw command line
        if self.command_line:
            self.draw_string(fb, 10 + 8 * 6, y_offset, self.command_line, COLOR_TEXT)
        
        # Draw cursor
        if self.cursor_visible:
            cursor_x = 10 + 8 * 6
            # Calculate actual cursor position considering Korean characters
            for char in self.command_line:
                if ord(char) >= 128:
                    cursor_x += 14
                else:
                    cursor_x += 6
            
            for dy in range(12):
                for dx in range(2):
                    px = cursor_x + dx
                    py = y_offset + dy
                    if 0 <= px < WIDTH and 0 <= py < HEIGHT:
                        offset = (py * WIDTH + px) * 4
                        fb[offset:offset+4] = struct.pack('<I', COLOR_CURSOR)

