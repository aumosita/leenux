class Framebuffer:
    def __init__(self):
        self.fb = bytearray(WIDTH * HEIGHT * PIXEL_SIZE)
    
    def set_pixel(self, x, y, color):
        if 0 <= x < WIDTH and 0 <= y < HEIGHT:
            offset = (y * WIDTH + x) * PIXEL_SIZE
            self.fb[offset:offset+4] = struct.pack('<I', color)
    
    def fill_rect(self, x, y, w, h, color):
        for dy in range(h):
            for dx in range(w):
                self.set_pixel(x + dx, y + dy, color)
    
    def draw_char(self, x, y, char, color):
        """Draw character using 5x8 font (matching kernel)"""
        if char not in FONT_5X8:
            return
        
        char_data = FONT_5X8[char]
        for row in range(8):
            byte = char_data[row]
            for bit in range(5):
                if byte & (0x10 >> bit):  # Bit 4,3,2,1,0
                    self.set_pixel(x + bit, y + row, color)
    
    def draw_string(self, x, y, text, color):
        """Draw string (matching kernel's draw_string)"""
        cx = x
        for char in text:
            self.draw_char(cx, y, char, color)
            cx += 6  # 5 pixels + 1 spacing
    
    def save(self, filename):
        with open(filename, 'wb') as f:
            f.write(self.fb)

